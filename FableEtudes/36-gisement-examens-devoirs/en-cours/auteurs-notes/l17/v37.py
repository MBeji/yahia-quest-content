# Double résolution mission 37 : chemin 1 = coordonnées exactes ; chemin 2 = théorèmes (formules).
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lib"))
from geo import *
from sympy import sqrt, Rational as R, simplify, acos, pi
import m37_figs as F
A, B, C, I, O, D, E, Fp, G, N, H = F.A, F.B, F.C, F.I, F.O, F.D, F.E, F.F, F.G, F.N, F.H

def ok(cond, msg):
    assert cond, "ÉCHEC : " + msg
    print("  ok :", msg)

print("Q1")
ok(on_circle(D, I, 3) and perp(D, A, D, B), "ABD rectangle en D (D sur le cercle de diamètre [AB])")
ok(zero(dist(D, A) - dist(D, B)), "DA = DB")
ok(not zero(dist(D, A) - dist(A, B)), "ABD n'est pas équilatéral")
ok(not perp(B, A, B, D), "pas d'angle droit en B")
print("Q2")
ok(simplify(dist(B, D) - 3 * sqrt(2)) == 0 and simplify(sqrt(18) - 3 * sqrt(2)) == 0 and simplify(6 / sqrt(2) - 3 * sqrt(2)) == 0, "BD = 3√2 (coordonnées ; √18 ; AB/√2)")
ok(simplify(sqrt(36 + 36) - 6 * sqrt(2)) == 0 and 36 / 2 == 18, "distracteurs 6√2 = √(36+36) ; 18 = BD² ; 3 = AB/2")
print("Q3")
ok(zero(ang_cos(A, E, C) - ang_cos(A, D, B)) and zero(ang_cos(A, D, B) - sqrt(2) / 2), "angle EAC = angle DAB = 45°")
ok(perp(E, A, E, C) and zero(dist(E, A) - dist(E, C)), "AEC rectangle isocèle en E")
ok(not zero(dist(A, E) - dist(A, D)), "(info) AEC ≠ ABD : propriété non transférable")
print("Q4")
ok(simplify(dist(E, C) - 4 * sqrt(2)) == 0 and simplify(sqrt(32) - 4 * sqrt(2)) == 0 and simplify(8 / sqrt(2) - 4 * sqrt(2)) == 0, "EC = 4√2")
ok(simplify(sqrt(128) - 8 * sqrt(2)) == 0, "distracteur 8√2 = √(64+64)")
print("Q5")
ok(dist(D, I) == 3 and dist(D, G) == 2 and zero(dist(D, G) - R(2, 3) * dist(D, I)), "DI = 3, DG = 2")
ok(R(1, 3) * 3 == 1 and R(1, 2) * 3 == R(3, 2) and R(2, 3) * 6 == 4, "distracteurs 1, 3/2, 4")
print("Q6")
ok(perp(O, E, A, C) and dist(O, B) == 2 and dist(O, Fp) == 2 and same(Fp, mid(O, E)), "(OE)⊥(AC), OB=2, OF=2, F milieu de [OE]")
ok(simplify(dist(B, Fp) - 2 * sqrt(2)) == 0 and not same(Fp, mid(B, D)) and simplify(dist(B, D) / 2 - 3 * sqrt(2) / 2) == 0, "F n'est pas le milieu de [BD] (BF = 2√2 ≠ 3√2/2)")
ok(dist(O, Fp) != 3, "OF ≠ 3")
# chemin 2 (Thalès) : (FO) ∥ (DI), BO/BI = OF/DI
ok(par(Fp, O, D, I) and zero(dist(B, O) / dist(B, I) - dist(O, Fp) / dist(D, I)), "OF par Thalès : BO/BI = OF/DI -> OF = 2")
print("Q7")
ok(par(E, Fp, D, G) and perp(E, Fp, A, C) and perp(D, G, A, C), "(EF) ∥ (DG), tous deux ⊥ (AC)")
ok(dist(E, Fp) == 2 and dist(D, G) == 2, "EF = DG = 2")
ok(same(mid(E, G), mid(Fp, D)), "EFGD parallélogramme (diagonales [EG],[FD] même milieu)")
ok(not same(mid(E, Fp), mid(D, G)), "[EF] et [DG] n'ont pas le même milieu (ce sont des côtés)")
print("Q8")
ok(simplify(dist(A, E) - 4 * sqrt(2)) == 0 and simplify(dist(N, Fp) - 2 * sqrt(2)) == 0 and simplify(dist(A, E) / 2 - dist(N, Fp)) == 0, "AE = 4√2 ; NF = AE/2 = 2√2")
ok(par(N, Fp, A, E) and same(N, mid(O, A)) and same(Fp, mid(O, E)), "(NF) ∥ (AE), N et F milieux")
ok(dist(O, A) / 2 == 2 and dist(O, E) / 2 == 2, "distracteur 2 = OA/2 = OE/2")
ok(dist(O, A) == 4 and dist(O, E) == 4 and simplify(dist(N, Fp) - 4) != 0, "distracteur 4 = OA = OE (côté entier pris pour NF)")
print("Q9")
ok(par(N, Fp, A, E) and par(Fp, G, A, E) and par(Fp, G, E, D), "(NF) ∥ (AE) ; (FG) ∥ (ED) ⊂ (AE)")
ok(collinear(N, G, Fp) and par(N, G, A, E), "N, G, F alignés ; (NG) ∥ (AE) (vrai mais à démontrer)")
print("Q10")
ok(simplify(dist(Fp, G) - sqrt(2)) == 0 and simplify(dist(E, D) - sqrt(2)) == 0 and simplify(dist(E, A) - dist(D, A) - sqrt(2)) == 0 and between(D, A, E), "FG = ED = EA − DA = √2 (D entre A et E)")
ok(simplify(dist(D, A) + dist(E, A) - 7 * sqrt(2)) == 0 and simplify(dist(D, A) * dist(E, A) - 24) == 0 and simplify(dist(D, A) - 3 * sqrt(2)) == 0, "distracteurs 7√2, 24, 3√2")
ok(simplify(dist(Fp, G) / dist(N, Fp) - R(1, 2)) == 0 and simplify(7 * sqrt(2) / (2 * sqrt(2)) - R(7, 2)) == 0 and simplify(3 * sqrt(2) / (2 * sqrt(2)) - R(3, 2)) == 0 and simplify(dist(Fp, G) / dist(E, A) - R(1, 4)) == 0, "FG/NF = 1/2 ; distracteurs 7/2, 3/2, 1/4 (= FG/EA)")
ok(same(G, mid(N, Fp)) and simplify(dist(N, Fp) - 2 * dist(Fp, G)) == 0 and between(G, N, Fp), "G milieu de [NF] : NF = 2 FG")
print("Q11")
ok(perp(D, G, N, B) and perp(N, G, B, D) and perp(B, G, D, N), "G sur les trois hauteurs de DNB : orthocentre")
ok(not same(mid(N, B), I) and same(mid(N, B), O), "le milieu de [NB] est O ≠ I : (DG) n'est pas une médiane de DNB")
ok(not zero(dist(G, D) - dist(G, N)) and dist(G, D) == 2 and simplify(dist(G, N) - sqrt(2)) == 0, "GD = 2 ≠ GN = √2 : pas le centre du cercle circonscrit")
ok(not same(G, mid(D, I)) and between(I, N, B) , "G n'est pas le milieu de [DI] ; I ∈ [NB] (pied de la hauteur de D)")
print("Q12")
ok(perp(B, G, D, N) and collinear(B, G, H) and perp(G, H, D, N), "(BG) ⊥ (DN), H ∈ (BG)")
ok(not same(H, mid(D, N)), "H n'est pas le milieu de [DN]")
ok(not perp(D, G, D, N), "(info) (DG) n'est pas ⊥ (DN) : l'option d est insuffisante")
print("M37 : toutes les vérifications passent")
